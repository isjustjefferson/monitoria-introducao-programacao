# Questão 8
# Enunciado: Qual é a saída do código abaixo?
# -------------------------------------------------------------

n = 4072
soma = 0
qtd = 0
while n > 0:
    soma += n % 10
    n //= 10
    qtd += 1
print(qtd, soma)

# -------------------------------------------------------------
# A) 4 13
# B) 3 13
# C) 4 4072
# D) 4 11
# E) 0 13
# -------------------------------------------------------------

# -------------------------------------------------------------
# Resposta: C) 4 13
# -------------------------------------------------------------